"""
Regenerate the snapshot of Standvirtual's makes, models and sub-models.

    cd backend
    python scripts/refresh_sv_taxonomy.py
    python scripts/refresh_sv_taxonomy.py --out-dir /tmp/sv     # dry run: write elsewhere, diff by hand
    python scripts/refresh_sv_taxonomy.py --html page.html      # parse a saved search page, no request

One request: the search page embeds the whole filter tree in its __NEXT_DATA__
(urqlState -> filters.states). Writes

    app/scrapers/sv_models_data.py   SV_MAKES, SV_MODELS
    app/scrapers/sv_series_data.py   SV_SERIES

The tree still names its filters filter_enum_make / filter_enum_model /
filter_enum_engine_code (checked 2026-11-17). Only the filters the site reports
as *applied* to a search moved, in mid-November 2026, to one combined
make_model_engine_code = "make|model" (see standvirtual.applied_make_model);
this script does not read those.

Run it when the site adds models (a new model is not matched by name until
then; its search is discarded as unscoped, never wrong). Review the diff, and
check the result with scripts/audit_sv_slugs.py.
"""
import argparse
import datetime
import json
import os
import re
import sys

import httpx

BACKEND = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
URL = "https://www.standvirtual.com/carros"
HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    "Accept-Language": "pt-PT,pt;q=0.9,en;q=0.7",
    "Accept-Encoding": "gzip, deflate",
}

# Filter ids of the tree in filters.states (not the applied-filter names).
MAKE, MODEL, SUBMODEL = "filter_enum_make", "filter_enum_model", "filter_enum_engine_code"

HOW = ("Generated by scripts/refresh_sv_taxonomy.py from the filter data embedded in a\n"
       "search results page (__NEXT_DATA__ -> urqlState -> filters.states). Do not edit\n"
       "by hand.")


def _filter_states(html: str) -> list:
    m = re.search(r'<script id="__NEXT_DATA__"[^>]*>(.*?)</script>', html, re.S)
    if not m:
        sys.exit("no __NEXT_DATA__ in the page")
    for entry in json.loads(m.group(1))["props"]["pageProps"]["urqlState"].values():
        data = json.loads(entry.get("data") or "null")
        if isinstance(data, dict) and "filters" in data:
            return data["filters"]["states"]
    sys.exit("no filter data in the page")


def _taxonomy(states: list) -> tuple:
    """({make id: name}, {make id: {model id: name}}, {make id: {model id: {sub-model id: name}}})."""
    makes, models, series = {}, {}, {}
    for state in states:
        conditions = {c["filterId"]: c["value"] for c in (state.get("conditions") or [])}
        values = {v["id"]: v["name"] for group in state["values"] for v in group["values"]}
        make = conditions.get(MAKE)
        if state["filterId"] == MAKE and not conditions:
            makes = values
        elif state["filterId"] == MODEL and make:
            models[make] = values
        elif state["filterId"] == SUBMODEL and make:
            series.setdefault(make, {})[conditions[MODEL]] = values
    return makes, models, series


def _pairs(values: dict) -> str:
    return ", ".join(f"{json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}"
                     for k, v in sorted(values.items()))


def render_models(makes: dict, models: dict, today: str) -> str:
    """Text of sv_models_data.py."""
    lines = ['"""', "Standvirtual's makes and their models, as the site's own search filter lists",
             f"them on {today} ({len(makes)} makes, {sum(len(m) for m in models.values())} models).", HOW,
             "See sv_models.py for how it is used.", "",
             "    SV_MAKES  = {make id: make name}",
             "    SV_MODELS = {make id: {model id: model name}}", '"""', "",
             "SV_MAKES = {"]
    lines += [f"    {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}," for k, v in sorted(makes.items())]
    lines += ["}", "", "SV_MODELS = {"]
    lines += [f"    {json.dumps(make)}: {{{_pairs(models[make])}}}," for make in sorted(models)]
    lines += ["}"]
    return "\n".join(lines) + "\n"


def render_series(series: dict, models: dict, today: str) -> str:
    """Text of sv_series_data.py."""
    n_series = sum(len(s) for s in series.values())
    n_variants = sum(len(v) for s in series.values() for v in s.values())
    lines = ['"""', 'Standvirtual\'s series ("Modelo") and their sub-models ("Sub-modelo"), for the',
             "makes the site files that way (BMW, Mercedes-Benz, Lexus and the Porsche 911),",
             f"on {today} ({n_series} series, {n_variants} sub-models).", HOW,
             "See sv_series.py for how it is used.", "",
             "    {make id: {series id: (series name, {sub-model id: sub-model name})}}", '"""', "",
             "SV_SERIES = {"]
    for make in sorted(series):
        lines.append(f"    {json.dumps(make)}: {{")
        for series_id in sorted(series[make]):
            name = models[make][series_id]
            lines.append(f"        {json.dumps(series_id)}: ({json.dumps(name, ensure_ascii=False)}, "
                         f"{{{_pairs(series[make][series_id])}}}),")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0].strip())
    ap.add_argument("--out-dir", default=os.path.join(BACKEND, "app", "scrapers"),
                    help="where to write sv_models_data.py and sv_series_data.py (default: app/scrapers)")
    ap.add_argument("--html", help="parse this saved search page instead of fetching the site")
    args = ap.parse_args()

    if args.html:
        with open(args.html, encoding="utf-8") as fh:
            html = fh.read()
    else:
        html = httpx.get(URL, headers=HEADERS, follow_redirects=True, timeout=30).text
    makes, models, series = _taxonomy(_filter_states(html))
    if len(makes) < 100 or len(models) < 100 or not series:
        sys.exit(f"implausible taxonomy: {len(makes)} makes, {len(models)} model lists, {len(series)} makes with series")
    today = datetime.date.today().isoformat()

    os.makedirs(args.out_dir, exist_ok=True)
    for name, text in (("sv_models_data.py", render_models(makes, models, today)),
                       ("sv_series_data.py", render_series(series, models, today))):
        with open(os.path.join(args.out_dir, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    n_series = sum(len(s) for s in series.values())
    n_variants = sum(len(v) for s in series.values() for v in s.values())
    print(f"{len(makes)} makes, {sum(len(m) for m in models.values())} models, {n_series} series, {n_variants} sub-models"
          f" -> {os.path.abspath(args.out_dir)}")


if __name__ == "__main__":
    main()
